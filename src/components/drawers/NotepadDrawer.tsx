import React, { useState, useMemo } from 'react';
import { useApp } from '../../context/AppContext';
import {
  X,
  Plus,
  Search,
  Pin,
  Trash2,
  Copy,
  Download,
  Eye,
  Edit3,
  Tag,
  Sparkles,
  Camera,
  Calendar,
  User,
  Check
} from 'lucide-react';
import { MarkdownRenderer } from '../common/MarkdownRenderer';

export const NotepadDrawer: React.FC = () => {
  const {
    isNotepadDrawerOpen,
    setIsNotepadDrawerOpen,
    notes,
    selectedNoteId,
    setSelectedNoteId,
    addNote,
    updateNote,
    deleteNote,
    showToast
  } = useApp();

  const [searchQuery, setSearchQuery] = useState('');
  const [selectedTag, setSelectedTag] = useState<string | null>(null);
  const [isPreviewMode, setIsPreviewMode] = useState(false);
  const [isCopied, setIsCopied] = useState(false);
  const [tagInput, setTagInput] = useState('');

  const allTags = useMemo(() => {
    const tagsSet = new Set<string>();
    notes.forEach(n => n.tags.forEach(t => tagsSet.add(t)));
    return Array.from(tagsSet);
  }, [notes]);

  const filteredNotes = useMemo(() => {
    return notes
      .filter(n => {
        const matchesQuery =
          !searchQuery.trim() ||
          n.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
          n.content.toLowerCase().includes(searchQuery.toLowerCase()) ||
          n.tags.some(t => t.toLowerCase().includes(searchQuery.toLowerCase()));

        const matchesTag = !selectedTag || n.tags.includes(selectedTag);

        return matchesQuery && matchesTag;
      })
      .sort((a, b) => {
        if (a.pinned && !b.pinned) return -1;
        if (!a.pinned && b.pinned) return 1;
        return new Date(b.updatedAt).getTime() - new Date(a.updatedAt).getTime();
      });
  }, [notes, searchQuery, selectedTag]);

  const activeNote = notes.find(n => n.id === selectedNoteId) || filteredNotes[0] || null;

  if (!isNotepadDrawerOpen) return null;

  const handleCreateNewNote = () => {
    const newNote = addNote({
      title: 'Untitled Document',
      content: '',
      tags: selectedTag ? [selectedTag] : ['general'],
      source: 'manual'
    });
    setSelectedNoteId(newNote.id);
    setIsPreviewMode(false);
    showToast('New note created', 'info');
  };

  const handleCopyNote = () => {
    if (!activeNote) return;
    navigator.clipboard
      .writeText(`${activeNote.title}\n\n${activeNote.content}`)
      .then(() => {
        setIsCopied(true);
        setTimeout(() => setIsCopied(false), 2000);
        showToast('Note copied to clipboard', 'success');
      })
      .catch(() => showToast('Clipboard access denied', 'error'));
  };

  const handleExportNote = () => {
    if (!activeNote) return;
    const blob = new Blob([`# ${activeNote.title}\n\n${activeNote.content}`], {
      type: 'text/markdown;charset=utf-8'
    });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${activeNote.title.replace(/[^a-z0-9]/gi, '_').toLowerCase()}.md`;
    link.click();
    URL.revokeObjectURL(url);
    showToast('Exported note as .md', 'info');
  };

  const handleAddTag = (e: React.KeyboardEvent) => {
    if (e.key === 'Enter' && tagInput.trim() && activeNote) {
      e.preventDefault();
      const clean = tagInput.trim().toLowerCase();
      if (!activeNote.tags.includes(clean)) {
        updateNote(activeNote.id, { tags: [...activeNote.tags, clean] });
      }
      setTagInput('');
    }
  };

  const handleRemoveTag = (tagToRemove: string) => {
    if (!activeNote) return;
    updateNote(activeNote.id, {
      tags: activeNote.tags.filter(t => t !== tagToRemove)
    });
  };

  const getSourceIcon = (source: string) => {
    switch (source) {
      case 'playground':
        return (
          <span title="Saved from Playground">
            <Sparkles className="h-3 w-3 text-theme-accent" />
          </span>
        );
      case 'snap-to-notes':
        return (
          <span title="Extracted from Snap-to-Notes">
            <Camera className="h-3 w-3 text-theme-accent" />
          </span>
        );
      case 'scheduler':
        return (
          <span title="Generated by Scheduler">
            <Calendar className="h-3 w-3 text-theme-accent" />
          </span>
        );
      default:
        return (
          <span title="Manual Document">
            <User className="h-3 w-3 text-theme-muted" />
          </span>
        );
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex justify-end bg-black/50 backdrop-blur-sm animate-fade-in transition-colors duration-180">
      <div className="relative flex h-full w-full max-w-4xl flex-col border-l border-theme-border bg-theme-main text-theme-primary shadow-warm-lg">
        {/* Top Header */}
        <div className="flex h-16 items-center justify-between border-b border-theme-border px-6 bg-theme-sidebar/50">
          <div className="flex items-center gap-3">
            <h2 className="font-editorial text-base font-semibold text-theme-primary">
              Shared Knowledge &amp; Notepad
            </h2>
            <span className="rounded-btn bg-theme-elevated px-2 py-0.5 text-xs text-theme-muted border border-theme-border font-mono">
              {notes.length} {notes.length === 1 ? 'doc' : 'docs'}
            </span>
          </div>

          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={handleCreateNewNote}
              className="inline-flex items-center gap-1.5 rounded-btn bg-theme-brand px-3 py-1.5 text-xs font-semibold text-theme-surface hover:bg-theme-brandHover transition-all shadow-warm-sm"
            >
              <Plus className="h-3.5 w-3.5 stroke-[2.5]" />
              New Document
            </button>
            <button
              type="button"
              onClick={() => setIsNotepadDrawerOpen(false)}
              className="rounded-btn p-2 text-theme-secondary hover:bg-theme-surface hover:text-theme-primary transition-colors"
            >
              <X className="h-4 w-4" />
            </button>
          </div>
        </div>

        {/* Content Body: Left Column (List) + Right Column (Editor) */}
        <div className="grid flex-1 grid-cols-1 md:grid-cols-12 overflow-hidden">
          {/* Notes Sidebar List (5 columns) */}
          <div className="flex flex-col max-h-56 md:max-h-none border-b md:border-b-0 md:border-r border-theme-border md:col-span-5 overflow-hidden bg-theme-sidebar/30">
            {/* Search & Tag Filter */}
            <div className="p-3 border-b border-theme-border space-y-2">
              <div className="relative">
                <Search className="absolute left-3 top-1/2 -translate-y-1/2 h-3.5 w-3.5 text-theme-muted" />
                <input
                  type="text"
                  value={searchQuery}
                  onChange={e => setSearchQuery(e.target.value)}
                  placeholder="Search documents or #tags..."
                  className="w-full rounded-btn border border-theme-border bg-theme-elevated pl-9 pr-3 py-1.5 text-xs text-theme-primary placeholder:text-theme-muted focus:border-theme-accent focus:outline-none"
                />
              </div>

              {allTags.length > 0 && (
                <div className="flex flex-wrap gap-1 max-h-16 overflow-y-auto pt-1">
                  <button
                    type="button"
                    onClick={() => setSelectedTag(null)}
                    className={`rounded px-2 py-0.5 text-[10px] font-mono uppercase transition-colors ${
                      selectedTag === null
                        ? 'bg-theme-accentLight text-theme-accent font-semibold border border-theme-borderStrong'
                        : 'bg-theme-elevated text-theme-muted hover:text-theme-primary border border-theme-border'
                    }`}
                  >
                    all
                  </button>
                  {allTags.map(tag => (
                    <button
                      key={tag}
                      type="button"
                      onClick={() => setSelectedTag(selectedTag === tag ? null : tag)}
                      className={`rounded px-2 py-0.5 text-[10px] font-mono transition-colors ${
                        selectedTag === tag
                          ? 'bg-theme-accentLight text-theme-accent font-semibold border border-theme-borderStrong'
                          : 'bg-theme-elevated text-theme-muted hover:text-theme-primary border border-theme-border'
                      }`}
                    >
                      #{tag}
                    </button>
                  ))}
                </div>
              )}
            </div>

            {/* Note Item Cards */}
            <div className="flex-1 overflow-y-auto divide-y divide-theme-border/50 p-2.5 space-y-1">
              {filteredNotes.length === 0 ? (
                <div className="p-6 text-center text-xs text-theme-muted">
                  No documents match filter.
                </div>
              ) : (
                filteredNotes.map(n => {
                  const isSelected = activeNote?.id === n.id;
                  return (
                    <div
                      key={n.id}
                      onClick={() => setSelectedNoteId(n.id)}
                      className={`group cursor-pointer rounded-card p-3 transition-all duration-160 ${
                        isSelected
                          ? 'bg-theme-surface border border-theme-borderStrong shadow-warm-sm'
                          : 'hover:bg-theme-surface/70 border border-transparent'
                      }`}
                    >
                      <div className="flex items-center justify-between gap-1">
                        <div className="flex items-center gap-1.5 min-w-0">
                          {n.pinned && <Pin className="h-3 w-3 text-theme-accent shrink-0 fill-theme-accent" />}
                          <h4 className="font-editorial text-xs font-semibold truncate text-theme-primary">
                            {n.title || 'Untitled Document'}
                          </h4>
                        </div>
                        <div className="flex items-center gap-1 shrink-0">
                          {getSourceIcon(n.source)}
                        </div>
                      </div>

                      <p className="mt-1 line-clamp-2 text-[11px] text-theme-secondary leading-relaxed">
                        {n.content.replace(/[#*`>-]/g, '').slice(0, 90) || 'Empty document...'}
                      </p>

                      <div className="mt-2 flex items-center justify-between text-[10px] text-theme-muted font-mono">
                        <span>{new Date(n.updatedAt).toLocaleDateString([], { month: 'short', day: 'numeric' })}</span>
                        <div className="flex gap-1 overflow-hidden">
                          {n.tags.slice(0, 2).map(tag => (
                            <span key={tag} className="text-theme-accent">#{tag}</span>
                          ))}
                        </div>
                      </div>
                    </div>
                  );
                })
              )}
            </div>
          </div>

          {/* Active Note Editor (7 columns) */}
          <div className="flex flex-col md:col-span-7 bg-theme-surface overflow-hidden">
            {activeNote ? (
              <>
                {/* Note Action Toolbar */}
                <div className="flex items-center justify-between border-b border-theme-border px-5 py-2.5 bg-theme-sidebar/40">
                  <div className="flex items-center gap-2">
                    <button
                      type="button"
                      onClick={() => setIsPreviewMode(!isPreviewMode)}
                      className={`inline-flex items-center gap-1.5 rounded-btn px-2.5 py-1 text-xs font-medium transition-colors border ${
                        isPreviewMode
                          ? 'bg-theme-accentLight text-theme-accent border-theme-borderStrong'
                          : 'bg-theme-elevated text-theme-secondary hover:text-theme-primary border-theme-border'
                      }`}
                    >
                      {isPreviewMode ? <Edit3 className="h-3 w-3" /> : <Eye className="h-3 w-3" />}
                      <span>{isPreviewMode ? 'Edit' : 'Preview'}</span>
                    </button>
                    <span className="text-[10px] text-theme-muted font-mono">
                      {activeNote.content.split(/\s+/).filter(Boolean).length} words
                    </span>
                  </div>

                  <div className="flex items-center gap-1.5">
                    <button
                      type="button"
                      onClick={() => updateNote(activeNote.id, { pinned: !activeNote.pinned })}
                      className={`p-1.5 rounded-btn border border-theme-border transition-colors ${
                        activeNote.pinned
                          ? 'text-theme-accent bg-theme-accentLight border-theme-borderStrong'
                          : 'text-theme-muted hover:text-theme-primary hover:bg-theme-elevated'
                      }`}
                      title={activeNote.pinned ? 'Unpin' : 'Pin to top'}
                    >
                      <Pin className="h-3.5 w-3.5" />
                    </button>
                    <button
                      type="button"
                      onClick={handleCopyNote}
                      className="p-1.5 rounded-btn border border-theme-border text-theme-muted hover:text-theme-primary hover:bg-theme-elevated transition-colors"
                      title="Copy Markdown"
                    >
                      {isCopied ? <Check className="h-3.5 w-3.5 text-theme-accent" /> : <Copy className="h-3.5 w-3.5" />}
                    </button>
                    <button
                      type="button"
                      onClick={handleExportNote}
                      className="p-1.5 rounded-btn border border-theme-border text-theme-muted hover:text-theme-primary hover:bg-theme-elevated transition-colors"
                      title="Export .md"
                    >
                      <Download className="h-3.5 w-3.5" />
                    </button>
                    <button
                      type="button"
                      onClick={() => {
                        if (confirm('Delete this document?')) {
                          deleteNote(activeNote.id);
                          showToast('Document deleted', 'info');
                        }
                      }}
                      className="p-1.5 rounded-btn border border-theme-border text-theme-muted hover:text-rose-500 hover:border-rose-300 transition-colors"
                      title="Delete document"
                    >
                      <Trash2 className="h-3.5 w-3.5" />
                    </button>
                  </div>
                </div>

                {/* Title & Tags */}
                <div className="px-6 pt-5 pb-3 border-b border-theme-border/60 space-y-2.5">
                  <input
                    type="text"
                    value={activeNote.title}
                    onChange={e => updateNote(activeNote.id, { title: e.target.value })}
                    placeholder="Document Title..."
                    className="w-full bg-transparent font-editorial text-xl font-bold text-theme-primary placeholder:text-theme-muted focus:outline-none"
                  />

                  {/* Tags Pill Bar */}
                  <div className="flex flex-wrap items-center gap-1.5">
                    <Tag className="h-3 w-3 text-theme-muted" />
                    {activeNote.tags.map(tag => (
                      <span
                        key={tag}
                        className="inline-flex items-center gap-1 rounded bg-theme-elevated px-2 py-0.5 text-[11px] font-mono text-theme-accent border border-theme-border"
                      >
                        #{tag}
                        <button
                          type="button"
                          onClick={() => handleRemoveTag(tag)}
                          className="hover:text-rose-500 text-theme-muted"
                        >
                          ×
                        </button>
                      </span>
                    ))}
                    <input
                      type="text"
                      value={tagInput}
                      onChange={e => setTagInput(e.target.value)}
                      onKeyDown={handleAddTag}
                      placeholder="+ tag (Enter)"
                      className="rounded bg-transparent px-2 py-0.5 text-[11px] font-mono text-theme-primary placeholder:text-theme-muted focus:outline-none"
                    />
                  </div>
                </div>

                {/* Editor / Markdown Preview Area */}
                <div className="flex-1 overflow-y-auto p-6">
                  {isPreviewMode ? (
                    <MarkdownRenderer content={activeNote.content || '*Empty document content.*'} />
                  ) : (
                    <textarea
                      value={activeNote.content}
                      onChange={e => updateNote(activeNote.id, { content: e.target.value })}
                      placeholder="Write in Markdown... Use # Headers, - Lists, ```code``` blocks"
                      className="h-full w-full resize-none bg-transparent font-mono text-xs leading-relaxed text-theme-primary placeholder:text-theme-muted focus:outline-none"
                    />
                  )}
                </div>
              </>
            ) : (
              <div className="flex flex-1 flex-col items-center justify-center p-8 text-center text-theme-muted">
                <p className="font-editorial text-sm">Select a document or create a new one to begin.</p>
              </div>
            )}
          </div>
        </div>
      </div>
    </div>
  );
};
